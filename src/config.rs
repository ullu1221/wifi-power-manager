//! Persistent configuration management.
//! Features atomic writes and synchronization with NetworkManager.

use crate::state::PowerSaveMode;
use std::fs::{self, File};
use std::io::{self, Write};
use std::path::Path;

pub const DEFAULT_CONFIG_PATH: &str = "/etc/wifi-pm.conf";
pub const NM_CONFIG_PATH: &str = "/etc/NetworkManager/conf.d/99-wifi-powersave.conf";

/// Read saved power save mode from configuration file
#[must_use]
pub fn load_config(path: &str) -> Option<PowerSaveMode> {
    let content = fs::read_to_string(path).ok()?;
    for line in content.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with('#') || trimmed.is_empty() {
            continue;
        }
        if let Some((k, v)) = trimmed.split_once('=') {
            if k.trim().eq_ignore_ascii_case("WIFI_POWERSAVE") {
                return PowerSaveMode::parse(v);
            }
        }
    }
    None
}

/// Atomically write configuration to the specified path
pub fn atomic_write_file(path: &str, content: &str) -> io::Result<()> {
    let target = Path::new(path);
    if let Some(parent) = target.parent() {
        if !parent.exists() {
            fs::create_dir_all(parent)?;
        }
    }

    let tmp_path = format!("{path}.tmp.{}", std::process::id());
    {
        let mut f = File::create(&tmp_path)?;
        f.write_all(content.as_bytes())?;
        f.sync_all()?;
    }

    fs::rename(&tmp_path, target)
}

/// Persist chosen power save mode to `/etc/wifi-pm.conf` and `/etc/NetworkManager/conf.d/`
pub fn save_config(mode: PowerSaveMode) -> io::Result<()> {
    // 1. Write /etc/wifi-pm.conf
    let mode_str = mode.as_iw_str();
    let pm_content = format!(
        "# wifi-pm configuration\n\
         # Automatically generated by wifi-pm\n\
         # Valid options: on, off\n\
         WIFI_POWERSAVE={mode_str}\n"
    );
    atomic_write_file(DEFAULT_CONFIG_PATH, &pm_content)?;

    // 2. Sync with NetworkManager if directory exists
    if Path::new("/etc/NetworkManager").exists() {
        let nm_code = mode.as_nm_code();
        let nm_content = format!(
            "# Generated by wifi-pm controller\n\
             # 2 = Disable power save (Low latency / Gaming CAM mode)\n\
             # 3 = Enable power save (Battery economy)\n\
             [connection]\n\
             wifi.powersave={nm_code}\n"
        );
        let _ = atomic_write_file(NM_CONFIG_PATH, &nm_content);
    }

    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_load_config_parser() {
        let sample = "# comment\nWIFI_POWERSAVE=off\n";
        let tmp_file = format!("/tmp/test_wifi_pm_config_{}.conf", std::process::id());
        fs::write(&tmp_file, sample).unwrap();

        let loaded = load_config(&tmp_file);
        assert_eq!(loaded, Some(PowerSaveMode::Off));

        let _ = fs::remove_file(&tmp_file);
    }
}
